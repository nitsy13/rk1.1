import sys
sys.setrecursionlimit(10000)

def fill(a, x, y, c, b):
    if x < 0 or y < 0 or y >= len(a) or x >= len(a[0]):
        return
    if a[y][x] == b or a[y][x] == c:
        return
    a[y][x] = c
    fill(a, x+1, y, c, b)
    fill(a, x-1, y, c, b)
    fill(a, x, y+1, c, b)
    fill(a, x, y-1, c, b)

